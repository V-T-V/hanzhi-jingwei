def parse():
    up, xia = load_sections()
    # 域分与总计边界
    i_zj = xia.find("本秦京師為内史")
    i_fs = xia.find("凡民函五常之性")
    states_region = xia[:i_zj]
    zongji = xia[i_zj:i_fs]
    yf = xia[i_fs:]

    # 志序 = 上卷起至京兆尹条
    i_jing = up.find("京兆尹(")
    xvxu = up[:i_jing]
    up_rest = up[i_jing:]

    # 顺序定位 103 条目
    segs, pos, pool = [], 0, up_rest + states_region
    bounds = []
    for raw, disp, skey in JUNGS:
        key = raw + "("
        p = pool.find(key, pos)
        assert p >= 0, "未找到条目 %s（%s）" % (raw, key)
        bounds.append((raw, disp, skey, p))
        pos = p + 1
    end_cap = [b[3] for b in bounds[1:]] + [len(pool)]   # 末条（長沙國）至流域末
    entries = []
    for (raw, disp, skey, p), e in zip(bounds, end_cap):
        entries.append({"raw": raw, "disp": disp, "skey": skey,
                        "text": pool[p:e], "juan": "上" if p < len(up_rest) else "下"})

    out_states = []
    diag = []
    for ent in entries:
        text = ent["text"]
        head_end = len(ent["raw"])
        head_note = ""
        if text[head_end:head_end + 1] == "(":
            close = text.find(")", head_end)
            head_note = text[head_end + 1:close]
            struct_start = close + 1
        else:
            struct_start = head_end
        # 户口数字：去注文本上匹配（口数与○縣间常夹師古注；「戸」偶讹「尸」）
        main_t = re.sub(r"\([^)]*\)", "", text)
        m = re.search(r"[戸户戶尸]([〇零一二三四五六七八九十百千萬]+)口([〇零一二三四五六七八九十百千萬]+)", main_t)
        mx = re.search(r"○縣([〇零一二三四五六七八九十百]+)", main_t)
        hu, kou, nx = None, None, None
        if m:
            hu, kou = cn2int(m.group(1)), cn2int(m.group(2))
        if mx:
            nx = cn2int(mx.group(1))
        # 原文户口句（逐字保留，注意中夹注者取去注句）
        hukou_v = ""
        mv = re.search(r"([戸户戶尸][〇零一二三四五六七八九十百千萬]+口[〇零一二三四五六七八九十百千萬]+)", main_t)
        if mv:
            hukou_v = mv.group(1)
        # 县域：原文 ○縣N 之后（数字与首县间或无空格，数字限定数字字）
        mo = re.search(r"○縣[〇零一二三四五六七八九十百]+\u3000?", text)
        county_region = text[mo.end():] if mo else ""
        counties = tokenize_counties(county_region)
        # 合并裸县整理（书证：两汉志县目；全角空格缺如致两县连写）
        fixed = []
        for cn2, note in counties:
            key = (ent["disp"], nname(cn2))
            if key in SPLIT_FIX:
                for part in SPLIT_FIX[key]:
                    fixed.append([part, note])
            else:
                fixed.append([cn2, note])
        counties = fixed
        ent["_c"] = counties          # [(名, 注)] 供 build_text 全文重构
        ent["_hn"] = head_note
        ent["_hv"] = hukou_v
        ent["_xv"] = mo.group(0) if mo else ""
        # 徽标（注中实证；鐵/鐡 二形并计）
        badges = {
            "tie": text.count("鐵官") + text.count("鐡官"), "yan": text.count("鹽官"),
            "gong": text.count("工官"), "ju": text.count("橘官"),
            "mu": text.count("木官"), "shui": text.count("都水"),
            "ci": text.count("祠"), "mang": text.count("莽曰"),
        }
        ok = nx is not None and len(counties) == nx
        st = {
            "n": ent["disp"], "raw": ent["raw"], "bu": BU_OF[ent["skey"]],
            "juan": ent["juan"], "hu": hu, "kou": kou, "nx": nx,
            "hukou_v": nname(hukou_v),
            "xian": [re.sub(r"&KR\d{4};", "□", nname(c[0])) for c in counties],
            "seat": re.sub(r"&KR\d{4};", "□", nname(counties[0][0])) if counties else None,
            "ok": ok, "badges": badges, "hn": len(head_note),
            "yt": len(re.sub(r"\s", "", text)),   # 条目文量（正文+注，3D 文柱据）
        }
        if not ok:
            st["rawlist"] = True
        if ent["skey"] in SEAT_NOTE:
            st["seat_note"] = SEAT_NOTE[ent["skey"]]
        co = COORDS.get(ent["skey"])
        st["c"] = [co[0], co[1]] if co else None
        st["now"] = co[2] if co else None
        st["conf"] = co[3] if co else None
        st["src"] = "derived" if co else None
        out_states.append(st)
        if not ok:
            diag.append((ent["disp"], ent["juan"], nx, len(counties), counties[-3:]))
    return out_states, diag, xvxu, zongji, yf, up, xia, entries


