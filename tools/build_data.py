def tokenize_counties(region):
    """县名实证：括号注锚定；全角空格=裸县分隔。返回 [(名, 注)]"""
    out, buf, note, cur = [], [], [], None
    i, n = 0, len(region)
    while i < n:
        ch = region[i]
        if ch == "（" or ch == "）":
            i += 1
            continue
        if ch == "(":
            if buf:
                cur = ["".join(buf), []]
                out.append(cur)
                buf = []
            note_open = i + 1
            depth_end = region.find(")", note_open)
            if depth_end < 0:
                depth_end = n
            if cur is not None:
                cur[1].append(region[note_open:depth_end])
            i = depth_end + 1
            continue
        if ch == ")":
            i += 1
            continue
        if ch == "\u3000":            # 全角空格：裸县分隔
            if buf:
                out.append(["".join(buf), []])
                buf = []
                cur = None
            i += 1
            continue
        buf.append(ch)
        i += 1
    if buf:
        if cur is not None and out and out[-1] is cur:
            pass
        out.append(["".join(buf), []])
    # 修正：尾部 buf 若与上一 token 同引用（连续注后无名），合并入注
    return [(a, "/".join(b)) for a, b in out if a]


