def nname(s):
    return "".join(NAME_NORM.get(ch, ch) for ch in s)


def clean(seg):
    s = re.sub(r"<pb:[^>]*>", "", seg)
    s = s.replace("¶", "").replace("\n", "")
    return s


def load_sections():
    t = open(RAW, encoding="utf-8").read()
    up = clean(t[:t.find("卷二十八上考證")])
    up = up[up.find("昔在黃帝"):]        # 剥卷首题名行
    up = re.sub(r"[\u3000\s]*前漢書卷二十八上#\+PROPERTY.*$", "", up)  # 尾部 org 杂讯
